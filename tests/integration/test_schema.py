"""The migrations create exactly what the platform and plug-ins declare (ADR 0029)."""

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Column, Integer, Table

from guildhall.platform.database import DatabaseSettings
from guildhall.plugins.synthetic import metadata as synthetic_metadata

REPO_ROOT = Path(__file__).resolve().parents[2]


@pytest.fixture
def alembic_config(test_database_settings: DatabaseSettings) -> Config:
    config = Config(toml_file=str(REPO_ROOT / "pyproject.toml"))
    config.attributes["url"] = test_database_settings.url()
    return config


def test_migrations_match_every_declared_table(alembic_config: Config) -> None:
    command.check(alembic_config)  # raises if a migration is missing


def test_a_table_declared_without_a_migration_is_detected(
    alembic_config: Config,
) -> None:
    table = Table("synthetic_unmigrated", synthetic_metadata, Column("id", Integer))
    try:
        with pytest.raises(AutogenerateDiffsDetected, match="synthetic_unmigrated"):
            command.check(alembic_config)
    finally:
        synthetic_metadata.remove(table)
